-- Sintaxis nueva: Hyprland 0.55+ con API Lua oficial

hl.config({ autogenerated = false })

-- =============================================================================
-- 1. RUTAS Y VARIABLES
-- =============================================================================
local mod = "SUPER"
local wall = "/home/javier/dotfiles/.config/hypr/wallpapers/957277.jpg"
local hp_config = "/home/javier/dotfiles/.config/hypr/hyprpaper.conf"

-- =============================================================================
-- 2. MONITOR
-- =============================================================================
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = 1.25,
})

-- =============================================================================
-- 3. AUTOSTART
-- =============================================================================
hl.on("hyprland.start", function()
    hl.exec_cmd("waybar -c /home/javier/dotfiles/.config/waybar/waybar-hyprl/config -s /home/javier/dotfiles/.config/waybar/waybar-hyprl/style.css")
    hl.exec_cmd("swaync")
    hl.exec_cmd("hyprpaper -c " .. hp_config)
    hl.exec_cmd("hyprctl hyprpaper wallpaper ', " .. wall .. "'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface gtk-theme 'Dream-Violet-Dark-GTK'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface icon-theme 'Papirus-Dark'")
end)

-- =============================================================================
-- 4. CONFIGURACIÓN GENERAL Y ANIMACIONES
-- =============================================================================
hl.config({
    general = {
        gaps_in     = 10,
        gaps_out    = 4,
        border_size = 4,
        col = {
            active_border   = { colors = { "rgba(bf00ffff)", "rgba(4b0082ff)" }, angle = 45 },
            inactive_border = "rgba(2a2a2aff)",
        },
        layout = "dwindle",
    },
	gestures = {
        workspace_swipe = true,
